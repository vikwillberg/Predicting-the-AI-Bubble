"""Regenerate the auto-updating results block in README.md."""

from __future__ import annotations

import json
import re

import pandas as pd

from .. import config
from .style import pct

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def block(r: dict) -> str:
    v = r["verdict"]
    burst = r["survival"]["burst"]["targets"]
    bear = r["survival"]["bear"]["targets"]
    ai = burst["AI20"]
    ri = r["risk_index"]["composite"]
    sk = r["survival"]["burst"]["metrics"]["h12"]["p_ens"]
    ex = v.get("lppls_ex_ante")
    cap = r["fundamentals"]["capex"]["latest"]
    rd = r["fundamentals"]["reverse_dcf"]["scenarios"]["IPO ($1.5T)"]["required_revenue_b"]
    lines = [
        START,
        f"*Auto-generated by the pipeline from `reports/results.json`. Data as of **{r['data_as_of']}**.*",
        "",
        "| Question | ICARUS answer |",
        "|---|---|",
        f"| Is AI in a bubble? | **{'Yes' if v['is_bubble'] else 'Not by ICARUS criteria'}**: Bubble Risk Index "
        f"**{ri['score']:.0f}/100** (range {ri['dirichlet_p10']:.0f}-{ri['dirichlet_p90']:.0f} under random pillar weights); "
        f"PSY test finds explosive growth in {', '.join(v['psy_explosive_series_since_2023']) or 'none'} since 2023 |",
        f"| Where are we? | **{v['stage'].capitalize()}**: AI-20 peaked {v['ai20_peak_date']}, now "
        f"{-v['ai20_drawdown_from_peak']:.1%} below; HMM regime **{v['regime']}** "
        f"({pct(v['regime_probabilities']['stress'])}); {r['systemic']['ai20_n_in_bear']} of {r['systemic']['ai20_n_members']} members in bear markets |",
        f"| P(AI-20 falls 40%+ within 12 months) | **{pct(ai['p12'])}** (80% CI {pct(ai['p12_interval'][0])}-{pct(ai['p12_interval'][1])}) |",
        f"| P(AI-20 falls 40%+ within 24 months) | **{pct(ai['p24'])}** (80% CI {pct(ai['p24_interval'][0])}-{pct(ai['p24_interval'][1])}) |",
        f"| When? | Most likely burst month **{v['most_likely_burst_month']}**; median, if it bursts within 24 months: "
        f"**{v['conditional_median_burst_month']}**; dot-com clock equivalent: {v['dotcom_clock_equivalent_peak']} |",
    ]
    for tk in ("^NDX", "^GSPC"):
        t = bear.get(tk, {})
        if t and not t.get("already_happened"):
            lines.append(f"| P({t['name']} bear market, -20%, within 12 months) | {pct(t['p12'])} |")
    if ex:
        lines.append(f"| LPPLS bubble clock (ex-ante) | On {ex['forecast_made']} it put the critical time at "
                     f"**{ex['tc_median']}**; the AI-20 peaked **{ex['peak']}** ({ex['error_days']:+d} days) |")
    lines += [
        f"| Capex strain | Hyperscalers spent **{cap['capex_to_ocf']:.2f}x** their operating cash flow on capex last quarter; "
        f"{cap['companies_spending_more_than_ocf']} of {cap['companies']} spent more than they generated |",
        f"| Anthropic IPO at $1.5T | Requires ~**${rd['p50']:.0f}B** revenue by "
        f"{r['fundamentals']['reverse_dcf']['target_year']} (80% range ${rd['p10']:.0f}-{rd['p90']:.0f}B) |",
        f"| Model skill (out of sample) | 12-month AUC **{sk['auc']:.2f}**, Brier skill **{sk['brier_skill_vs_climatology']:+.0%}** vs base rate |",
        "",
        END,
    ]
    return "\n".join(lines)


def run() -> None:
    path = config.ROOT / "README.md"
    r = json.loads((config.REPORTS / "results.json").read_text())
    text = path.read_text()
    if START in text and END in text:
        text = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block(r), text, flags=re.S)
        path.write_text(text)
